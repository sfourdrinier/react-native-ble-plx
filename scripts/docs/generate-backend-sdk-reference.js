// scripts/docs/generate-backend-sdk-reference.js

'use strict'

const fs = require('fs')
const path = require('path')

const root = path.resolve(__dirname, '../..')
const capabilitySourcePath = path.join(root, 'src/backend-contract/capabilities.ts')
const tckContractSourcePath = path.join(root, 'src/tck/contracts.ts')
const tckScenarioSourcePath = path.join(root, 'src/tck/scenarios.ts')
const outputPath = path.join(root, 'docs/generated/BACKEND_SDK_REFERENCE.md')
const checkOnly = process.argv.slice(2).includes('--check')

function extractStringUnion(source, typeName) {
  const match = new RegExp(`export type ${typeName}\\s*=\\s*([\\s\\S]*?)\\n+export type `).exec(source)
  if (match === null || match[1] === undefined) {
    throw new Error(`Unable to locate canonical ${typeName} union`)
  }
  const values = [...match[1].matchAll(/'([^']+)'/g)].map(item => item[1]).filter(Boolean)
  if (values.length === 0) {
    throw new Error(`Canonical ${typeName} union has no literal values`)
  }
  return values
}

function requireScenarioImplementations(ids, scenarioSource) {
  for (const id of ids) {
    if (!scenarioSource.includes(`id: '${id}'`)) {
      throw new Error(`Canonical TCK scenario ${id} has no scenario definition`)
    }
  }
}

function markdownList(values) {
  return values.map(value => `- \`${value}\``).join('\n')
}

function render() {
  const capabilitySource = fs.readFileSync(capabilitySourcePath, 'utf8')
  const tckContractSource = fs.readFileSync(tckContractSourcePath, 'utf8')
  const tckScenarioSource = fs.readFileSync(tckScenarioSourcePath, 'utf8')
  const featureStates = extractStringUnion(capabilitySource, 'FeatureState')
  const evidenceLevels = extractStringUnion(capabilitySource, 'EvidenceLevel')
  const scenarioIds = extractStringUnion(tckContractSource, 'TckScenarioId')
  requireScenarioImplementations(scenarioIds, tckScenarioSource)

  return `<!-- docs/generated/BACKEND_SDK_REFERENCE.md -->

# Generated backend SDK reference

This file is generated by \`scripts/docs/generate-backend-sdk-reference.js\` from the canonical production contract. Do not edit it by hand; run \`pnpm docs:backend-sdk\` after a contract/TCK change.

## Capability states

${markdownList(featureStates)}

## Evidence levels

${markdownList(evidenceLevels)}

## Required TCK scenario identifiers

${markdownList(scenarioIds)}

## Authoring entrypoint

External backends import \`unified-ble-manager/backend-sdk\`. They define a \`BackendAuthoringDefinition\` with immutable author metadata, a \`BackendTckFactory\` that declares both the selected adapter and a known-unlisted stale selection, creates a backend plus \`TckScenarioController\` deterministic environment inputs for an exact scenario context, and feature suites. A fixture cannot return an executor, facts, proof scope, or receipt. \`createBackendAuthorDefinition()\` validates the declaration; \`runBackendAuthorTck()\` runs the complete base suite plus all applicable registered feature suites through runner-owned public-manager scenarios and creates the public \`verification: "runner-controlled"\` deterministic receipts. Backend instances are consumed once; self-authored or replayed results cannot be presented as conformance. \`inspectBackendCapabilities()\` projects runtime registry state, author-declared evidence, limitations, limits, and required TCK bindings without exposing implementation handles or labelling author evidence conformant.

The CLI-selected module must export \`unifiedBleBackend\`, an authoring definition. The Node-only CLI validates that the provider host kind is \`node\`, \`electron-main\`, or \`test\`; it never selects a browser or React Native radio path.

## Trace format v1

\`unified-ble-trace-v1\` contains ordered, bounded records with an ordinal, time, kind, event, dotted error cause, and four mandatory redaction markers. The schema has no peer, path, payload, or platform-message field. \`ubm trace validate <file>\` rejects malformed or unredacted input; \`ubm trace redact <file>\` strips unsupported fields and emits a redacted trace document without writing the source file.
`
}

const rendered = render()
if (checkOnly) {
  if (!fs.existsSync(outputPath)) {
    throw new Error(`Generated backend SDK reference is missing: ${path.relative(root, outputPath)}`)
  }
  const current = fs.readFileSync(outputPath, 'utf8')
  if (current !== rendered) {
    throw new Error(`Generated backend SDK reference is stale: ${path.relative(root, outputPath)}`)
  }
} else {
  fs.writeFileSync(outputPath, rendered)
}
