// scripts/docs/generate-platform-support.js

'use strict'

const fs = require('node:fs')
const path = require('node:path')
const { validateManifest, validateManifestCollection } = require('../evidence/validate-evidence-manifest')

const root = path.resolve(__dirname, '../..')
const recordsDirectory = path.join(root, 'evidence/v1/records')
const outputPath = path.join(root, 'docs/generated/PLATFORM_SUPPORT.md')
const checkOnly = process.argv.slice(2).includes('--check')

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, 'utf8'))
}

function evidenceRecords() {
  const recordPaths = fs
    .readdirSync(recordsDirectory, { withFileTypes: true })
    .filter(entry => entry.isFile() && entry.name.endsWith('.json'))
    .map(entry => path.join(recordsDirectory, entry.name))
    .sort((left, right) => left.localeCompare(right))
  if (recordPaths.length === 0) {
    throw new Error('No current evidence records exist beneath evidence/v1/records')
  }
  const records = recordPaths.map(recordPath => ({
    path: path.relative(root, recordPath).split(path.sep).join('/'),
    manifest: readJson(recordPath)
  }))
  const errors = []
  for (const record of records) {
    for (const error of validateManifest(record.manifest, root)) {
      errors.push(`${record.path}: ${error}`)
    }
  }
  errors.push(...validateManifestCollection(records))
  if (errors.length > 0) {
    throw new Error(`Platform-support generation rejected invalid evidence:\n${errors.map(error => `- ${error}`).join('\n')}`)
  }
  return records
}

function escapeCell(value) {
  return String(value).replaceAll('|', '\\|').replaceAll('\n', ' ')
}

function artifactBinding(manifest, packageName, packageVersion) {
  const artifact = manifest.subject.packageArtifact
  const exact =
    artifact.name === packageName &&
    artifact.version === packageVersion &&
    artifact.availability === 'available' &&
    typeof artifact.sha256 === 'string' &&
    artifact.sha256.length === 64
  return exact ? 'exact package artifact' : 'not bound to current package artifact'
}

function evidenceRow(record, packageName, packageVersion) {
  const manifest = record.manifest
  return [
    `\`${manifest.claim.id}@${String(manifest.claim.revision)}\``,
    `\`${manifest.subject.backend.id}\``,
    `\`${manifest.subject.platform.id}\``,
    `\`${manifest.subject.host.id}\``,
    manifest.claim.publishedSupportLabel,
    `${manifest.proof.level} / ${manifest.proof.status}`,
    artifactBinding(manifest, packageName, packageVersion),
    `[manifest](../../${record.path})`
  ]
    .map(escapeCell)
    .join(' | ')
}

function currentArtifactClaims(records, packageName, packageVersion) {
  return records.filter(record => artifactBinding(record.manifest, packageName, packageVersion) === 'exact package artifact')
}

function render() {
  const packageManifest = readJson(path.join(root, 'package.json'))
  const records = evidenceRecords()
  const exactClaims = currentArtifactClaims(records, packageManifest.name, packageManifest.version)
  const exactSection =
    exactClaims.length === 0
      ? 'No evidence record is bound to this exact package version and artifact. Consequently, this generated page makes no Preview, Live Preview, Supported, or Reliability-qualified platform claim for the current package.'
      : `The following ${String(exactClaims.length)} evidence record(s) are bound to the exact current package artifact. Their labels remain limited to the proof recorded in each manifest.`

  return `<!-- docs/generated/PLATFORM_SUPPORT.md -->

# Generated platform support evidence

This page is generated by \`scripts/docs/generate-platform-support.js\` from validated manifests beneath \`evidence/v1/records/\`. It is an evidence projection, not a static host capability matrix. Runtime feature availability comes only from the instantiated backend capability registry and can be inspected with \`ubm capabilities --backend <module>\`.

## Current package

\`${packageManifest.name}@${packageManifest.version}\`

${exactSection}

## Validated evidence records

| Claim | Backend | Platform | Host | Published label | Proof | Current artifact binding | Source |
| --- | --- | --- | --- | --- | --- | --- | --- |
${records.map(record => `| ${evidenceRow(record, packageManifest.name, packageManifest.version)} |`).join('\n')}

## Interpretation rules

- An Experimental, blocked, historical, compile-only, deterministic, or reported-unverified record is not live-radio proof.
- A platform label applies only to the exact artifact, backend, platform, host, scenarios, and limitations named by its manifest.
- Missing hardware blocks only the associated evidence label; it does not invent or remove runtime capabilities.
- Capability documentation must be compared with a runtime capability report for the instantiated backend. This page never infers support from a host name.
`
}

const rendered = render()
if (checkOnly) {
  if (!fs.existsSync(outputPath)) {
    throw new Error(`Generated platform support page is missing: ${path.relative(root, outputPath)}`)
  }
  if (fs.readFileSync(outputPath, 'utf8') !== rendered) {
    throw new Error(`Generated platform support page is stale: ${path.relative(root, outputPath)}`)
  }
} else {
  fs.writeFileSync(outputPath, rendered)
}
